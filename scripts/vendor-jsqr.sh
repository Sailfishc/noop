#!/bin/sh
# Vendors jsQR (github.com/cozmo/jsQR, Apache-2.0) into app/ui/jsqr.ts: the QR decoder the in-app scanner's web page
# runs (app/ui/qr-scanner.tsx). NSH apps have no npm at run time and the page is inline HTML, so the minified
# library is kept as a string. Checks the tarball against npm's published integrity; needs curl, openssl and bun.
#
#   scripts/vendor-jsqr.sh     write app/ui/jsqr.ts from jsqr@$VERSION
set -eu
VERSION=1.4.0
INTEGRITY="sha512-dxLob7q65Xg2DvstYkRpkYtmKm2sPJ9oFhrhmudT1dZvNFFTlroai3AWSpLey/w5vMcLBXRgOJsbXpdN9HzU/A=="
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
curl -fsSL --retry 3 -o "$TMP/jsqr.tgz" "https://registry.npmjs.org/jsqr/-/jsqr-$VERSION.tgz"
got="sha512-$(openssl dgst -sha512 -binary "$TMP/jsqr.tgz" | base64 | tr -d '\n')"
[ "$got" = "$INTEGRITY" ] || { echo "vendor-jsqr: integrity mismatch ($got)" >&2; exit 1; }
tar -xzf "$TMP/jsqr.tgz" -C "$TMP"
# Transpiled and minified only (nothing runs): its UMD wrapper sets self.jsQR in a page.
bun build "$TMP/package/dist/jsQR.js" --minify --format=cjs --target=browser --outfile="$TMP/jsqr.min.js" > /dev/null
if grep -qi "</script" "$TMP/jsqr.min.js"; then echo "vendor-jsqr: the library contains </script" >&2; exit 1; fi
{
  echo "// jsQR $VERSION (https://github.com/cozmo/jsQR), Apache-2.0 (app/ui/LICENSE-APACHE), minified."
  echo "// Generated by scripts/vendor-jsqr.sh: don't edit. Sets self.jsQR in the scanner's page (qr-scanner.tsx)."
  printf 'export const JSQR = '
  bun -e 'process.stdout.write(JSON.stringify(require("fs").readFileSync(process.argv[1], "utf8")))' "$TMP/jsqr.min.js"
  echo ";"
} > "$ROOT/app/ui/jsqr.ts"
echo "vendor-jsqr: wrote app/ui/jsqr.ts ($(wc -c < "$ROOT/app/ui/jsqr.ts") bytes)"
